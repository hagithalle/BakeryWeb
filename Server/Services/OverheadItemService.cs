using Microsoft.AspNetCore.Http;
using Microsoft.EntityFrameworkCore;
using Server.Data;
using Server.Models;
using Server.Services.Pricing;

namespace Server.Services
{
    public class OverheadItemService : IOverheadItemService
    {
        private readonly BakeryDbContext _context;
        private readonly PurchaseVatService _purchaseVat;
        // Every query below is limited to the current user's rows by BakeryDbContext's query filter,
        // and new rows are stamped with the current user's id when saved.
        public OverheadItemService(BakeryDbContext context, PurchaseVatService purchaseVat)
        {
            _context = context;
            _purchaseVat = purchaseVat;
        }

        public async Task<List<OverheadItem>> GetAllAsync()
        {
            return await _context.OverheadItems
                .OrderBy(x => x.Name)
                .ToListAsync();
        }

        public async Task<OverheadItem?> GetByIdAsync(int id)
        {
            return await _context.OverheadItems.FirstOrDefaultAsync(x => x.Id == id);
        }

        public async Task<OverheadItem> CreateAsync(OverheadItem item)
        {
            item.Id = 0; // ids are generated by the database, never taken from the client
            _purchaseVat.Validate(item);
            _context.OverheadItems.Add(item);
            await _context.SaveChangesAsync();
            return item;
        }

        public async Task<bool> UpdateAsync(int id, OverheadItem item)
        {
            var existing = await _context.OverheadItems.FirstOrDefaultAsync(x => x.Id == id);
            if (existing == null) return false;
            _purchaseVat.Validate(item);

            existing.Name = item.Name;
            existing.MonthlyCost = item.MonthlyCost;
            existing.IsActive = item.IsActive;
            existing.Type = item.Type;
            existing.Category = item.Category;
            PurchaseVatService.ApplyUpdate(existing, item);

            await _context.SaveChangesAsync();
            return true;
        }

        public async Task<bool> DeleteAsync(int id)
        {
            var existing = await _context.OverheadItems.FirstOrDefaultAsync(x => x.Id == id);
            if (existing == null) return false;

            _context.OverheadItems.Remove(existing);
            await _context.SaveChangesAsync();
            return true;
        }
    }
}
