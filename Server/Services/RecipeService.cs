using BakeryWeb.Server.Services;
using Microsoft.AspNetCore.Http;
using Microsoft.EntityFrameworkCore;
using Server.Data;
using Server.Models;
using Server.Validation;

namespace Server.Services
{
    public class RecipeService : IRecipeService
    {
        private readonly LogManager _logManager;
        private readonly BakeryDbContext _db;
        private readonly CostCalculatorService _costCalculator;
        private readonly ReferenceValidator _references;

        // Every query below is limited to the current user's recipes by BakeryDbContext's query filter,
        // and new recipes are stamped with the current user's id when saved.
        public RecipeService(BakeryDbContext db, CostCalculatorService costCalculator, LogManager logManager, ReferenceValidator references)
        {
            _db = db;
            _costCalculator = costCalculator;
            _logManager = logManager;
            _references = references;
        }

        public async Task<Recipe> CreateAsync(Recipe recipe)
        {
            _logManager.LogSuccess(nameof(RecipeService), nameof(CreateAsync), $"Recipe: Name={recipe.Name}, OutputUnits={recipe.OutputUnits}, " +
                $"Ingredients={recipe.Ingredients?.Count ?? 0}, Steps={recipe.Steps?.Count ?? 0}, BaseRecipes={recipe.BaseRecipes?.Count ?? 0}");

            // Every referenced ingredient / base recipe must belong to the current user (checked before any write).
            await _references.EnsureRecipeReferencesAsync(recipe, recipeId: null);

            // Ids are generated by the database, never taken from the client.
            recipe.Id = 0;
            foreach (var ri in recipe.Ingredients ?? new List<RecipeIngredient>()) ri.Id = 0;
            foreach (var rs in recipe.Steps ?? new List<RecipeStep>()) rs.Id = 0;
            foreach (var br in recipe.BaseRecipes ?? new List<RecipeItem>()) br.Id = 0;

            // Adding the recipe adds its ingredient lines, steps and base-recipe lines with it (one save, one
            // transaction). They must not be added again afterwards: that used to store every line twice.
            _db.Recipes.Add(recipe);
            await _db.SaveChangesAsync();

            _logManager.LogSuccess(nameof(RecipeService), nameof(CreateAsync), $"Recipe saved with ID: {recipe.Id}");
            return recipe;
        }

        public async Task<bool> DeleteAsync(int id)
        {
            var existing = await _db.Recipes.FirstOrDefaultAsync(r => r.Id == id);
            if (existing == null) return false;
            _db.Recipes.Remove(existing);
            await _db.SaveChangesAsync();
            return true;
        }

        public async Task<IEnumerable<Recipe>> GetAllAsync()
        {
            var recipes = await _db.Recipes
                .Include(r => r.Ingredients)
                .ThenInclude(ri => ri.Ingredient)
                .Include(r => r.Steps)
                .Include(r => r.BaseRecipes)
                .ThenInclude(br => br.BaseRecipe)
                .ToListAsync();

            // Costs (including nested sub-recipes) come from the calculator, never from what was loaded here.
            foreach (var r in recipes)
                _costCalculator.ApplyRecipeCosts(r);
            return recipes;
        }

        public async Task<Recipe?> GetByIdAsync(int id)
        {
            var recipe = await _db.Recipes
                .Include(r => r.Ingredients)
                .ThenInclude(ri => ri.Ingredient)
                .Include(r => r.Steps)
                .Include(r => r.BaseRecipes)
                .ThenInclude(br => br.BaseRecipe)
                .FirstOrDefaultAsync(r => r.Id == id);

            if (recipe != null)
                _costCalculator.ApplyRecipeCosts(recipe);

            return recipe;
        }

        public async Task<bool> UpdateAsync(int id, Recipe recipe)
        {
            var existing = await _db.Recipes
                .Include(r => r.Ingredients)
                .Include(r => r.Steps)
                .Include(r => r.BaseRecipes)
                .FirstOrDefaultAsync(r => r.Id == id);

            if (existing == null) return false;

            // Checked before anything is changed: references must be the user's own and must not create a cycle.
            await _references.EnsureRecipeReferencesAsync(recipe, recipeId: id);

            existing.Name = recipe.Name;
            existing.Description = recipe.Description;
            existing.Category = recipe.Category;
            existing.OutputUnits = recipe.OutputUnits;
            existing.OutputUnitType = recipe.OutputUnitType;
            existing.PrepTime = recipe.PrepTime;
            existing.BakeTime = recipe.BakeTime;
            existing.Temperature = recipe.Temperature;
            existing.RecipeType = recipe.RecipeType;
            if (!string.IsNullOrWhiteSpace(recipe.ImageUrl))
            {
                existing.ImageUrl = recipe.ImageUrl;
            }

            // Replace ingredients: simple approach - remove existing and add new
            _db.RecipeIngredients.RemoveRange(existing.Ingredients);
            existing.Ingredients.Clear();
            foreach (var ri in recipe.Ingredients)
            {
                existing.Ingredients.Add(new RecipeIngredient
                {
                    IngredientId = ri.IngredientId,
                    Quantity = ri.Quantity,
                    Unit = ri.Unit // הוסף את Unit
                });
            }

            // Replace steps
            _db.RecipeSteps.RemoveRange(existing.Steps);
            existing.Steps.Clear();
            foreach (var rs in recipe.Steps)
            {
                existing.Steps.Add(new RecipeStep
                {
                    Order = rs.Order,
                    Description = rs.Description,
                    EstimatedMinutes = rs.EstimatedMinutes
                });
            }

            // Replace base recipes (Recipe Composition)
            _db.RecipeItems.RemoveRange(existing.BaseRecipes);
            existing.BaseRecipes.Clear();
            foreach (var br in recipe.BaseRecipes)
            {
                existing.BaseRecipes.Add(new RecipeItem
                {
                    BaseRecipeId = br.BaseRecipeId,
                    Quantity = br.Quantity,
                    Unit = br.Unit
                });
            }

            await _db.SaveChangesAsync();
            return true;
        }
    }
}
