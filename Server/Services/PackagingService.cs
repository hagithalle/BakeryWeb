using Microsoft.AspNetCore.Http;
using Microsoft.EntityFrameworkCore;
using Server.Data;
using Server.Models;
using Server.Services.Pricing;

namespace Server.Services
{
    public class PackagingService : IPackagingService
    {
        private readonly BakeryDbContext _context;
        private readonly PurchaseVatService _purchaseVat;
        // Every query below is limited to the current user's rows by BakeryDbContext's query filter,
        // and new rows are stamped with the current user's id when saved.
        public PackagingService(BakeryDbContext context, PurchaseVatService purchaseVat)
        {
            _context = context;
            _purchaseVat = purchaseVat;
        }

        public async Task<List<Packaging>> GetAllAsync()
        {
            return await _context.Packagings
                .OrderBy(p => p.Id)
                .ToListAsync();
        }

        public async Task<Packaging?> GetByIdAsync(int id)
        {
            return await _context.Packagings.FirstOrDefaultAsync(p => p.Id == id);
        }

        public async Task<Packaging> CreateAsync(Packaging packaging)
        {
            packaging.Id = 0; // ids are generated by the database, never taken from the client
            _purchaseVat.Validate(packaging);
            _context.Packagings.Add(packaging);
            await _context.SaveChangesAsync();
            return packaging;
        }

        public async Task<bool> UpdateAsync(int id, Packaging packaging)
        {
            var existing = await _context.Packagings.FirstOrDefaultAsync(p => p.Id == id);
            if (existing == null) return false;
            _purchaseVat.Validate(packaging);

            existing.StockUnits = packaging.StockUnits;
            existing.Name = packaging.Name;
            existing.Cost = packaging.Cost;
            PurchaseVatService.ApplyUpdate(existing, packaging);

            await _context.SaveChangesAsync();
            return true;
        }

        public async Task<bool> DeleteAsync(int id)
        {
            var existing = await _context.Packagings.FirstOrDefaultAsync(p => p.Id == id);
            if (existing == null) return false;

            _context.Packagings.Remove(existing);
            await _context.SaveChangesAsync();
            return true;
        }
    }
}
